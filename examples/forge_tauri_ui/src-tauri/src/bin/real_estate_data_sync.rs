//! Headless authorized data sync for the real-estate agency mode.
//!
//! This binary reuses the same registry and scheduler as the Tauri UI, but it
//! can keep running without the visual app. It only indexes registered,
//! authorized sources and writes compact evidence/proof artifacts locally.

#[path = "../real_estate_harvester.rs"]
mod real_estate_harvester;

use serde_json::{json, Value};
use std::fs;
use std::path::PathBuf;
use std::thread;
use std::time::{Duration, SystemTime, UNIX_EPOCH};

fn main() {
    if let Err(err) = run() {
        eprintln!("[real-estate-data-sync] {err}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let args: Vec<String> = std::env::args().skip(1).collect();

    if args.iter().any(|arg| arg == "--uninstall-startup") {
        let report = uninstall_startup()?;
        print_json(report)?;
        return Ok(());
    }

    if args.iter().any(|arg| arg == "--startup-status") {
        let report = startup_status()?;
        print_json(report)?;
        return Ok(());
    }

    let store_path = resolve_store_arg(&args)?.unwrap_or(real_estate_harvester::default_store_path()?);

    if args.iter().any(|arg| arg == "--install-startup") {
        let report = install_startup(&store_path)?;
        print_json(report)?;
        return Ok(());
    }

    if args.iter().any(|arg| arg == "--status") {
        let snapshot = real_estate_harvester::snapshot(&store_path)?;
        print_json(json!(snapshot))?;
        return Ok(());
    }

    if args.iter().any(|arg| arg == "--once") {
        let reports = real_estate_harvester::run_all_once(&store_path)?;
        print_json(json!({
            "storePath": store_path,
            "reports": reports,
        }))?;
        return Ok(());
    }

    real_estate_harvester::start_background(store_path.clone())?;
    eprintln!(
        "[real-estate-data-sync] continuous authorized data sync started store={}",
        store_path.display()
    );
    loop {
        thread::sleep(Duration::from_secs(3600));
    }
}

fn resolve_store_arg(args: &[String]) -> Result<Option<PathBuf>, String> {
    let mut iter = args.iter();
    while let Some(arg) = iter.next() {
        if arg == "--store" {
            let Some(path) = iter.next() else {
                return Err("--store requires a path".to_string());
            };
            return Ok(Some(PathBuf::from(path)));
        }
    }
    Ok(None)
}

fn install_startup(store_path: &PathBuf) -> Result<Value, String> {
    let paths = startup_paths()?;
    fs::create_dir_all(&paths.startup_dir)
        .map_err(|e| format!("create Windows startup directory: {e}"))?;

    let exe_path = std::env::current_exe()
        .map_err(|e| format!("resolve current data sync executable: {e}"))?;
    let command = format!(
        "\"{}\" --store \"{}\"",
        exe_path.display(),
        store_path.display()
    );
    let launcher = format!(
        "' Auto-generated by Forge. Starts the real-estate data sync without opening a window.\r\n\
         Set WshShell = CreateObject(\"WScript.Shell\")\r\n\
         WshShell.Run \"{}\", 0, False\r\n",
        escape_vbs_string(&command)
    );
    fs::write(&paths.launcher_path, launcher)
        .map_err(|e| format!("write Windows startup launcher: {e}"))?;

    let metadata = json!({
        "installed": true,
        "installedAtMs": now_ms(),
        "exePath": exe_path,
        "storePath": store_path,
        "launcherPath": paths.launcher_path,
    });
    fs::write(
        &paths.metadata_path,
        serde_json::to_vec_pretty(&metadata)
            .map_err(|e| format!("serialize startup metadata: {e}"))?,
    )
    .map_err(|e| format!("write startup metadata: {e}"))?;

    Ok(json!({
        "installed": true,
        "launcherPath": paths.launcher_path,
        "metadataPath": paths.metadata_path,
        "metadata": metadata,
    }))
}

fn uninstall_startup() -> Result<Value, String> {
    let paths = startup_paths()?;
    let launcher_existed = remove_if_exists(&paths.launcher_path)?;
    let metadata_existed = remove_if_exists(&paths.metadata_path)?;
    Ok(json!({
        "installed": false,
        "launcherRemoved": launcher_existed,
        "metadataRemoved": metadata_existed,
        "launcherPath": paths.launcher_path,
        "metadataPath": paths.metadata_path,
    }))
}

fn startup_status() -> Result<Value, String> {
    let paths = startup_paths()?;
    let metadata = match fs::read(&paths.metadata_path) {
        Ok(bytes) => serde_json::from_slice::<Value>(&bytes).ok(),
        Err(_) => None,
    };
    Ok(json!({
        "installed": paths.launcher_path.exists(),
        "launcherPath": paths.launcher_path,
        "metadataPath": paths.metadata_path,
        "metadata": metadata,
    }))
}

struct StartupPaths {
    startup_dir: PathBuf,
    launcher_path: PathBuf,
    metadata_path: PathBuf,
}

fn startup_paths() -> Result<StartupPaths, String> {
    let appdata = std::env::var_os("APPDATA")
        .map(PathBuf::from)
        .ok_or_else(|| "APPDATA is not set; cannot resolve Windows startup folder".to_string())?;
    let startup_dir = appdata
        .join("Microsoft")
        .join("Windows")
        .join("Start Menu")
        .join("Programs")
        .join("Startup");
    Ok(StartupPaths {
        launcher_path: startup_dir.join("Forge Real Estate Data Sync.vbs"),
        metadata_path: startup_dir.join("Forge Real Estate Data Sync.json"),
        startup_dir,
    })
}

fn remove_if_exists(path: &PathBuf) -> Result<bool, String> {
    if !path.exists() {
        return Ok(false);
    }
    fs::remove_file(path).map_err(|e| format!("remove {}: {e}", path.display()))?;
    Ok(true)
}

fn escape_vbs_string(value: &str) -> String {
    value.replace('"', "\"\"")
}

fn now_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as u64
}

fn print_json(value: Value) -> Result<(), String> {
    println!(
        "{}",
        serde_json::to_string_pretty(&value).map_err(|e| format!("serialize report: {e}"))?
    );
    Ok(())
}
